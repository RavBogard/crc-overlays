#!/usr/bin/env node
// Writes companion/definitions.json: the action and feedback definitions this module version
// registers, as a JSON manifest the deck validator (lib/companion-deck/validate.ts) reads instead of
// parsing main.ts. Run by `npm run build` after tsc; it constructs the compiled module with a stub
// Companion context and no credential, so nothing leaves the machine. tests/definitions.test.ts holds
// the committed file equal to what the source registers.
//
// The file sits beside package.json, not in companion/: the packaged archive carries only the
// manifest and HELP.md there, and the TBI derivation refuses any other file.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const moduleRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
export const DEFINITIONS_PATH = join(moduleRoot, 'definitions.json')

const optionShape = (options) => (options ?? []).map((o) => ({ id: String(o.id), type: String(o.type) }))

/** Construct the module with a stub context, run init with no credential, return its definitions. */
export async function captureDefinitions(InstanceClass) {
  let actions = {}
  let feedbacks = {}
  const context = {
    _isInstanceContext: true, id: 'definitions', label: 'overlays', upgradeScripts: [],
    saveConfig: () => undefined, updateStatus: () => undefined, oscSend: () => undefined, recordAction: () => undefined,
    setActionDefinitions: (value) => { actions = value }, subscribeActions: () => undefined, unsubscribeActions: () => undefined,
    setFeedbackDefinitions: (value) => { feedbacks = value }, unsubscribeFeedbacks: () => undefined,
    checkFeedbacks: () => undefined, checkAllFeedbacks: () => undefined, checkFeedbacksById: () => undefined,
    setPresetDefinitions: () => undefined, setVariableDefinitions: () => undefined, setVariableValues: () => undefined,
    getVariableValue: () => undefined, sharedUdpSocketHandlers: new Map(),
    sharedUdpSocketJoin: async () => '', sharedUdpSocketLeave: async () => undefined, sharedUdpSocketSend: async () => undefined,
  }
  const noNetwork = async () => { throw new Error('definitions capture makes no requests') }
  const instance = new InstanceClass(context, { fetch: noNetwork, webSocketFactory: () => { throw new Error('definitions capture opens no sockets') } })
  await instance.init({ baseUrl: 'https://example.invalid', pairingCode: '' }, true, { controlKey: '', deviceToken: '' })
  await instance.destroy()
  const sorted = (record, map) => Object.fromEntries(Object.keys(record).sort().map((id) => [id, map(record[id])]))
  return {
    actions: sorted(actions, (a) => ({ name: String(a.name), options: optionShape(a.options) })),
    feedbacks: sorted(feedbacks, (f) => ({ name: String(f.name), type: String(f.type), options: optionShape(f.options) })),
  }
}

/** The manifest for this module version: its id and version from companion/manifest.json. */
export async function buildDefinitions(InstanceClass) {
  const manifest = JSON.parse(readFileSync(join(moduleRoot, 'companion', 'manifest.json'), 'utf8'))
  return {
    about: 'Generated by companion/scripts/write-definitions.mjs at module build time. Do not edit.',
    moduleId: manifest.id,
    version: manifest.version,
    ...(await captureDefinitions(InstanceClass)),
  }
}

export const formatDefinitions = (definitions) => JSON.stringify(definitions, null, 2) + '\n'

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { default: InstanceClass } = await import(pathToFileURL(join(moduleRoot, 'dist', 'main.js')).href)
  const definitions = await buildDefinitions(InstanceClass)
  writeFileSync(DEFINITIONS_PATH, formatDefinitions(definitions))
  console.log(`Wrote definitions.json: ${definitions.moduleId} ${definitions.version}, ${Object.keys(definitions.actions).length} actions, ${Object.keys(definitions.feedbacks).length} feedbacks`)
}
