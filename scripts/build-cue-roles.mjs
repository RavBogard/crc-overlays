#!/usr/bin/env node
// Writes content/cue-roles.json: each cue's role and set as CRC's deck binds it, derived from the
// deck model (lib/companion-deck/cue-roles.ts over the seed deck: CUE-MANIFEST.json + crc-seed-data.json).
// GET /api/catalog?include=slots carries it as the envelope's `roles` (lib/cue-roles.ts), so the
// Companion module groups and colours its presets the way the deck does.
//
//   node scripts/build-cue-roles.mjs [--check]
//
// --check writes nothing and fails when the committed file is stale; tests/cue-roles.test.ts runs the
// same comparison. Deterministic: the same manifest and seed data always give the same bytes.
import fs from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import { deckCueRoles } from '../lib/companion-deck/cue-roles.ts'
import { seedCrcDeck } from '../lib/companion-deck/seed.ts'

const root = path.resolve(import.meta.dirname, '..')
export const CUE_ROLES_PATH = path.join(root, 'content/cue-roles.json')
const MANIFEST = path.join(root, 'docs/planning/2026-09-23-overlay-consistency/companion/CUE-MANIFEST.json')
const SEED = path.join(root, 'lib/companion-deck/crc-seed-data.json')

export function buildCueRoles(manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf8')), seed = JSON.parse(fs.readFileSync(SEED, 'utf8'))) {
  return {
    about: 'Generated by scripts/build-cue-roles.mjs from the CRC seed deck (CUE-MANIFEST.json + lib/companion-deck/crc-seed-data.json). Do not edit; regenerate.',
    cues: deckCueRoles(seedCrcDeck(manifest, seed)),
  }
}
export const formatCueRoles = (value) => JSON.stringify(value, null, 1) + '\n'

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = formatCueRoles(buildCueRoles())
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(CUE_ROLES_PATH) ? fs.readFileSync(CUE_ROLES_PATH, 'utf8').replace(/\r\n/g, '\n') : ''
    if (current !== text) { console.error('content/cue-roles.json is stale; run node scripts/build-cue-roles.mjs'); process.exit(1) }
    console.log('content/cue-roles.json is current.')
  } else {
    fs.writeFileSync(CUE_ROLES_PATH, text)
    console.log(`Wrote content/cue-roles.json: ${Object.keys(JSON.parse(text).cues).length} cues.`)
  }
}
